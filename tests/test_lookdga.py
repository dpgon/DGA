'''
Characterization tests of lookdga.py: they pin the behaviour verified in docs/MVP.md (sections 1-7).
They must pass with the code as it is; if one fails after a change, something that worked is broken.
'''
import re

import pytest

from conftest import run

DATE = "2026-10-18"


def datalines(text):
    # -G prints status lines starting with "*" on stdout before the domains
    return [line for line in text.splitlines() if line and not line.startswith("*")]


def test_list():
    out = run("lookdga.py", "-L").stdout.splitlines()
    assert len(out) == 50
    assert out[0].startswith("banjori")
    assert "Banjori malware" in out[0]


def test_info_zloader():
    out = run("lookdga.py", "-m", "zloader", "-I").stdout
    assert "Max samples per date: 32" in out
    assert "Domain regular expresion: [a-y]{20}.com" in out


def test_generate_tinba():
    out = run("lookdga.py", "-m", "tinba", "-n", "5", "-G").stdout
    assert datalines(out) == ["newstatinru.ru", "justforyou0987.pw", "phpsitegooddecoder.com",
                              "santaluable.com", "santanyr.com"]


def test_generate_all_families():
    # 49 families x 3 + tempedreve, which only generates 1 domain per date
    out = run("lookdga.py", "-d", DATE, "-n", "3", "-G").stdout
    assert len(datalines(out)) == 148


def test_create_corpus():
    out = run("lookdga.py", "-d", DATE, "-n", "100", "-C").stdout
    rows = [line.split(",") for line in out.splitlines()]
    assert len(rows) == 5000
    assert len({row[1] for row in rows}) == 50


def test_firewall():
    # Always with -d: without it the date is datetime.now() with the time of day, and pizd, pykspa2 and
    # suppobox generate different domains depending on the hour. The count also depends on the time zone
    # (pykspa2 and suppobox use time.mktime): 1784 in UTC, which conftest.py enforces; 1794 in CEST
    domains = datalines(run("lookdga.py", "-d", DATE, "-F").stdout)
    assert len(domains) == 1784
    assert len(set(domains)) == len(domains)


def test_detect():
    # The false positive on google.com is a known limitation (docs/MVP.md section 6), not pinned here
    out = run("lookdga.py", "-D", "nvfowikhevmy.net").stdout
    assert "nvfowikhevmy.net could be generated by Tinba backdoor" in out


def test_unknown_family():
    out = run("lookdga.py", "-m", "noexiste", "-I").stdout
    assert "Unknown malware name" in out


@pytest.mark.slow
def test_bruteforce_tinba():
    out = run("lookdga.py", "-m", "tinba", "-B", "nvfowikhevmy.net").stdout
    assert "tinba: Domain nvfowikhevmy.net with config 1 is in 10 position" in out


def test_create_stdout_is_clean_csv():
    # C13: -C is redirected to a file (README), so stdout must only carry CSV rows; status goes to stderr
    proc = run("lookdga.py", "-m", "banjori", "-n", "2", "-C")
    rows = proc.stdout.splitlines()
    assert len(rows) == 2
    assert all(re.match(r'^[^,]+,[^,]+,[^,]*,\d{4}-\d{2}-\d{2}$', row) for row in rows)
    assert "* Generating domains for: banjori" in proc.stderr
    assert "* Generated 2 domains" in proc.stderr
